/** Reproducible, build-time-only Unicode/CLDR import. No runtime network requests. */
import { writeFile } from 'node:fs/promises';
import { SaxesParser } from 'saxes';

const unicode = 'https://unicode.org/Public/18.0.0/emoji/emoji-test.txt';
const cldr = 'https://raw.githubusercontent.com/unicode-org/cldr/release-49/common/';
const urls = [unicode, `${cldr}annotations/es.xml`, `${cldr}annotationsDerived/es.xml`];
const sources = await Promise.all(urls.map(async (url) => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return response.text();
}));
if (!sources[0].includes('# Version: 18.0')) throw new Error('Unexpected Unicode version');
const annotations = new Map();
for (const xml of sources.slice(1)) {
  let entry;
  const parser = new SaxesParser();
  parser.on('opentag', ({ name, attributes }) => {
    if (name === 'annotation') entry = { emoji: attributes.cp, tts: attributes.type === 'tts', text: '' };
  });
  parser.on('text', (text) => { if (entry) entry.text += text; });
  parser.on('closetag', ({ name }) => {
    if (name !== 'annotation' || !entry) return;
    const value = annotations.get(entry.emoji) ?? {};
    value[entry.tts ? 'label' : 'keywords'] = entry.text;
    annotations.set(entry.emoji, value);
    entry = undefined;
  });
  parser.write(xml).close();
}
const entries = [];
let category = '';
for (const line of sources[0].split('\n')) {
  if (line.startsWith('# group: ')) category = line.slice(9).trim();
  const match = /^([\dA-F ]+)\s*;\s*(fully-qualified|component)\s*#\s*\S+\s+E[\d.]+\s+(.+)$/.exec(line);
  if (!match) continue;
  const emoji = String.fromCodePoint(...match[1].trim().split(/\s+/).map((cp) => parseInt(cp, 16)));
  const annotation = annotations.get(emoji.replace(/\uFE0F/g, '')) ?? {};
  const tones = [...emoji].filter((cp) => cp.codePointAt(0) >= 0x1f3fb && cp.codePointAt(0) <= 0x1f3ff)
    .map((cp) => cp.codePointAt(0) - 0x1f3fa);
  entries.push({ emoji, label: annotation.label ?? match[3], keywords: `${annotation.keywords ?? ''} ${match[3]}`.trim(), category,
    tones: [...new Set(tones)] });
}
if (entries.length < 3900) throw new Error('Incomplete emoji catalog');
const header = `// Generated by scripts/generate-chat-emojis.mjs. Unicode 18.0 / CLDR 49.\n// Copyright Unicode, Inc. Unicode-3.0 license: https://www.unicode.org/license.txt\n`;
await writeFile(new URL('../packages/core/src/emojiSequences.ts', import.meta.url), `${header}export const EMOJI_UNICODE_VERSION = '18.0';\nexport const EMOJI_SEQUENCES: readonly string[] = ${JSON.stringify(entries.map((entry) => entry.emoji))};\n`);
await writeFile(new URL('../packages/app/src/lib/emojiCatalog.ts', import.meta.url), `${header}export interface EmojiEntry { emoji: string; label: string; keywords: string; category: string; tones: number[]; }\nexport const emojiCatalog: readonly EmojiEntry[] = ${JSON.stringify(entries)};\n`);
console.log(`Generated ${entries.length} emoji sequences with Spanish annotations.`);
